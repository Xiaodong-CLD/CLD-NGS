'''
This script is written to filter the deletions from the deletion vcf file generated by PINDEL/pindel2vcf.
The deletion vcf file generated by PINDEL contains SVTYPE=RPL, which means replications, but we do not need replications.
We'll filter out SVTYPE=DEL from the deletion vcf file geenrated by PINDEL/pindel2vcf.
'''
import os


def filter_deletions_from_pindel2vcf(deletion_file_path):
    #Check if the deltion file exists.
    if not os.path.exists(deletion_file_path):
        print("[Takeda Pipeline Message] PINDEL deletion file does not exists")
        return False

    #Read the deletion file.
    with open(deletion_file_path) as f:
        raw = f.read()

    deletion_data_rows = [i.split('\t') for i in raw.split('\n') if i != '' and not i.startswith("#")]
    filtered_deletion_results = []
    for deletion_entry in deletion_data_rows:
        #Info_index is the index/posiiton in the PINDEL deletion file which holds the information such as SV_Type in the vcf file.
        info_index = 7
        deletion_entry_info = deletion_entry[info_index]
        if "DEL" in deletion_entry_info and "HOMLEN=0" in deletion_entry_info:
            filtered_deletion_results.append(deletion_entry)

    #Write the results onto a new file.
    filtered_deletion_file_path = deletion_file_path.replace("_D", "_D_Filtered")
    with open(filtered_deletion_file_path, "w") as f:
        for entry in filtered_deletion_results:
            f.write("\t".join(entry))
            f.write("\n")

    return True

    
