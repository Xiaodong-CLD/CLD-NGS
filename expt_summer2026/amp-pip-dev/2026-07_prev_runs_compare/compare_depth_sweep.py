#!/usr/bin/env python3
"""Compare VarScan consensus calls at two mpileup depth-cap settings.

Reads the depth-sweep consensus files generated by mpileup_depth_sweep.py
under ``<run_dir>/Results/<sample>/depth-sweep/`` and compares VarFreq at
two depth modes (default: d=8000 vs d=0).  Output goes to --output-dir in
the same TSV format used by compare_runs.py so that comparison_summary.py
can read it.

Usage (from the 2026-07_prev_runs_compare/ directory):
  python compare_depth_sweep.py \\
      /home/robolab/cindy_ren/ngs/amp-pip-dev/runs/T3_rebuild \\
      --old-depth 8000 --new-depth 0 \\
      --output-dir comparison/TLA_d8000_vs_d0

Reconstructed Aug 2026 from shell history after accidental deletion.
"""
import argparse
import csv
import glob
import os
import sys


def parse_consensus(path):
    """Parse a VarScan consensus VCF into {position: {Ref, Var, VarFreq, ...}}."""
    rows = {}
    if not os.path.isfile(path):
        return rows
    with open(path) as fh:
        header = fh.readline().rstrip("\n").split("\t")
        idx = {c: i for i, c in enumerate(header)}
        for line in fh:
            cols = line.rstrip("\n").split("\t")
            if len(cols) < len(header):
                continue
            try:
                pos = int(cols[idx["Position"]])
            except (KeyError, ValueError):
                continue
            row = dict(zip(header, cols))
            rows[pos] = row
    return rows


def _freq(s):
    try:
        return float(s.rstrip("%"))
    except (ValueError, TypeError, AttributeError):
        return None


def _write_tsv(path, rows, fieldnames):
    if not rows:
        return
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=fieldnames, delimiter="\t",
                           extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)


def discover_samples(run_dir):
    """Find samples with depth-sweep consensus files."""
    pattern = os.path.join(run_dir, "Results", "*", "depth-sweep")
    samples = []
    for sweep_dir in sorted(glob.glob(pattern)):
        sample = os.path.basename(os.path.dirname(sweep_dir))
        samples.append((sample, sweep_dir))
    return samples


def compare_depths(sample, sweep_dir, old_d, new_d, output_dir):
    """Compare consensus calls at two depth settings for one sample."""
    old_path = os.path.join(sweep_dir, f"{sample}.d{old_d}.consensus.vcf")
    new_path = os.path.join(sweep_dir, f"{sample}.d{new_d}.consensus.vcf")
    old_data = parse_consensus(old_path)
    new_data = parse_consensus(new_path)

    if not old_data and not new_data:
        print(f"  [consensus] No data for either d={old_d} or d={new_d}")
        return {"sample": sample}

    all_pos = sorted(set(old_data) | set(new_data))
    matched = []
    old_only = []
    new_only = []

    for pos in all_pos:
        if pos in old_data and pos in new_data:
            old_freq_s = old_data[pos].get("VarFreq", "")
            new_freq_s = new_data[pos].get("VarFreq", "")
            old_f = _freq(old_freq_s)
            new_f = _freq(new_freq_s)
            delta = None
            if old_f is not None and new_f is not None:
                delta = new_f - old_f
            matched.append({
                "Position": pos,
                "Ref": old_data[pos].get("Ref", ""),
                "VarAllele": old_data[pos].get("Var", old_data[pos].get("VarAllele", "")),
                "OldFreq": old_freq_s,
                "NewFreq": new_freq_s,
                "DeltaFreq": f"{delta:+.2f}pp" if delta is not None else ".",
            })
        elif pos in old_data:
            old_only.append({
                "Position": pos,
                "Ref": old_data[pos].get("Ref", ""),
                "VarAllele": old_data[pos].get("Var", old_data[pos].get("VarAllele", "")),
                "VarFreq": old_data[pos].get("VarFreq", ""),
            })
        else:
            new_only.append({
                "Position": pos,
                "Ref": new_data[pos].get("Ref", ""),
                "VarAllele": new_data[pos].get("Var", new_data[pos].get("VarAllele", "")),
                "VarFreq": new_data[pos].get("VarFreq", ""),
            })

    prefix = os.path.join(output_dir, f"{sample}.consensus")
    if matched:
        _write_tsv(f"{prefix}.matched.tsv", matched,
                   ["Position", "Ref", "VarAllele", "OldFreq", "NewFreq", "DeltaFreq"])
    if old_only:
        _write_tsv(f"{prefix}.old_only.tsv", old_only,
                   ["Position", "Ref", "VarAllele", "VarFreq"])
    if new_only:
        _write_tsv(f"{prefix}.new_only.tsv", new_only,
                   ["Position", "Ref", "VarAllele", "VarFreq"])

    print(f"  [consensus] matched={len(matched)}  "
          f"d{old_d}_only={len(old_only)}  d{new_d}_only={len(new_only)}")

    return {
        "sample": sample,
        "snp_old": str(len(old_data)), "snp_new": str(len(new_data)),
        "snp_matched": str(len(matched)),
        "snp_old_only": str(len(old_only)), "snp_new_only": str(len(new_only)),
        "indel_old": "0", "indel_new": "0", "indel_matched": "0",
        "indel_old_only": "0", "indel_new_only": "0",
    }


def main():
    parser = argparse.ArgumentParser(
        description="Compare VarScan consensus at two mpileup depth caps.")
    parser.add_argument("run_dir",
                        help="Run directory with Results/<sample>/depth-sweep/.")
    parser.add_argument("--old-depth", type=int, default=8000,
                        help="Old (baseline) mpileup -d value (default: 8000).")
    parser.add_argument("--new-depth", type=int, default=0,
                        help="New mpileup -d value (default: 0 = unlimited).")
    parser.add_argument("--output-dir", required=True,
                        help="Directory for comparison TSVs.")
    args = parser.parse_args()

    os.makedirs(args.output_dir, exist_ok=True)
    samples = discover_samples(args.run_dir)
    if not samples:
        print(f"No depth-sweep samples found under {args.run_dir}/Results/",
              file=sys.stderr)
        return 1

    print(f"Comparing d={args.old_depth} vs d={args.new_depth} "
          f"for {len(samples)} sample(s)")

    summaries = []
    for sample, sweep_dir in samples:
        print(f"\n=== {sample} ===")
        summaries.append(
            compare_depths(sample, sweep_dir, args.old_depth, args.new_depth,
                           args.output_dir))

    summary_path = os.path.join(args.output_dir, "summary.tsv")
    fields = ["sample",
              "snp_old", "snp_new", "snp_matched", "snp_old_only", "snp_new_only",
              "indel_old", "indel_new", "indel_matched", "indel_old_only", "indel_new_only"]
    _write_tsv(summary_path, summaries, fields)
    print(f"\nSummary written to {summary_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
